"""The generated sets the rows of Checks 3 and 6 are asked of (plan 5.1, 5.5).

A set is generated by ``fixture/plant/generate.py``, built through the pipeline
replica, and counted by ``fixture/plant/count.py`` on the chunk files of that very
build. The expected values of a row come from that count, from the shard's own
index and from the team's tokenizer (Megatron's own, built as its preprocessing
builds it). None comes from the tool.

Three sizes. ``small`` is this folder's own: 800 records, built in about a minute,
so that the comparisons can be seen to work. ``10k`` and ``100k`` are the sizes
the plan names (5.1); their tests carry the markers ``slow`` and ``megatron``.

Two builds of a set:

- ``capture``: capture on, seeded, round-robin, tokenized, through the replica's
  command line (docs/replica.md section 7). The replica registers each shard with
  its tokenizer input ``<shard>.input`` and its capture map.
- ``no-capture``: capture off, unseeded shuffles, then recovered. The replica
  holds the recipe (``replica.fixture.build_set_store``), so that the store of a
  set and the table's store ``no-capture`` are recovered by one rule.

The set-ups of README section 7 for Check 3 (the recovery maps beside the capture
map, the swapped twin lines, the changed line) are applied here to a copy of the
capture store, through the tool's public calls for a run made without the wrapper
(docs/tokenmap.md section 7, docs/recovery.md section 2). The command line has a
``recover`` command (docs/cli.md); a set-up is not a question, so it is not asked
through it: one process holds the team's tokenizer for every shard of the set, which
is also the tokenizer that gives the expected values.
"""

from __future__ import annotations

import importlib.util
import json
import os
import re
import shutil
import subprocess
import sys
import tomllib
from dataclasses import dataclass, field
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SPEC = REPO / "fixture" / "spec" / "fixture_spec.toml"
PLANT = REPO / "fixture" / "plant"
MEGATRON_VARIABLE = "WATERWHITE_MEGATRON_ENV"

LAYOUT = "round-robin"
PARTITIONED = "partitioned"
# The store name of a shard of a generated set (docs/replica.md section 5): its tokenizer
# input and its sanitizer input are files beside it, named by what follows the shard.
# A round-robin layout registers numbered chunks, ``<prefix>/shard-NN``.
SHARD_NAME = re.compile(r"[^/]+/shard-\d+")
# A partitioned layout registers its shards as ``set/<shard>``: one per source file of the set,
# named by the file (``shard-A``), and the shard ``shard-gen`` for all generation outputs
# (docs/replica.md, the table "What set.toml does not say").
PARTITIONED_PREFIX = "set"
GENERATION_SHARD = "shard-gen"
CAPTURE, NO_CAPTURE = "capture", "no-capture"
JOBS = 4  # tokenizer runs at a time

SMALL = "small"
# The generator's parameters per size. The small set is the one the tests of the
# replica and of the plant use. The 10k and 100k sets are the plan's (docs/plant.md
# section 7.1): seed 1, every other option at its default.
SIZES: dict[str, dict] = {
    SMALL: dict(records=800, seed=7, length=160, pairs=24, sanitizer_cases=3),
    "10k": dict(records=10_000, seed=1),
    "100k": dict(records=100_000, seed=1),
}
# Dedup is on in the 10k set and off in the 100k set (plan 5.1), and off in the
# small one, so that both members of a pair reach a shard there too.
DEDUP = {SMALL: False, "10k": True, "100k": False}
BUILD_TIMEOUT = {SMALL: 900.0, "10k": 3600.0, "100k": 4 * 3600.0}

CHANGED_TEXT = "This line was changed after the shard was tokenized."

STATE_RECOVERED = "recovered"  # the two recovery maps beside the capture map
STATE_TWIN_SWAP = "t.twin-swap"
STATE_VERIFICATION_FAILS = "t.verification-fails"


class SetError(Exception):
    """A generated set could not be generated, built or counted as the tests need."""


class Unavailable(Exception):
    """Something a row needs is not there: not built yet, or not on this machine.
    The row is skipped with this reason; it is not a pass."""


def megatron_root() -> Path | None:
    value = os.environ.get(MEGATRON_VARIABLE, "")
    return Path(value).resolve() if value else None


def need_megatron() -> Path:
    root = megatron_root()
    if root is None:
        raise Unavailable(f"needs the Megatron environment: {MEGATRON_VARIABLE} is not set")
    return root


def load_script(file: str):
    """``fixture/plant`` is a folder of scripts, not a package: load one by file."""
    name = f"acceptance_plant_{Path(file).stem}"
    if name not in sys.modules:
        spec = importlib.util.spec_from_file_location(name, PLANT / file)
        module = importlib.util.module_from_spec(spec)
        sys.modules[name] = module
        spec.loader.exec_module(module)
    return sys.modules[name]


def source_names(set_folder) -> tuple[str, ...]:
    """The names of the source files of a set, from the ``[sources.*]`` tables of its
    ``set.toml``: the shard of a partitioned layout is named by its source file."""
    with open(Path(set_folder) / "set.toml", "rb") as f:
        declared = tomllib.load(f).get("sources")
    if not isinstance(declared, dict) or not declared:
        raise SetError(f"set.toml in {Path(set_folder).name} declares no source")
    return tuple(Path(entry["file"]).stem if isinstance(entry, dict) and "file" in entry else key
                 for key, entry in declared.items())


def layout_shards(instances, layout: str, set_folder) -> list[str]:
    """The store names of the shards a layout registers, out of the instances of a build:
    the round-robin chunks, or a partitioned layout's shard of each source file and its
    shard of generation outputs. What the documents say a layout registers decides, and
    never what the tool registered: a companion of a shard (``<shard>.input``) and every
    other instance never match, and a shard that was not written is simply not listed."""
    if layout == LAYOUT:
        wanted = SHARD_NAME
    elif layout == PARTITIONED:
        shards = [f"shard-{name}" for name in source_names(set_folder)] + [GENERATION_SHARD]
        wanted = re.compile(re.escape(PARTITIONED_PREFIX) + "/(?:"
                            + "|".join(map(re.escape, shards)) + ")")
    else:
        raise SetError(f"no shard list is fixed for the layout {layout!r}")
    return sorted(name for name in instances if wanted.fullmatch(name))


def read_rows(path: Path) -> list[dict]:
    with open(path, encoding="utf-8") as f:
        return [json.loads(line) for line in f.read().split("\n") if line != ""]


def tokenizer_table() -> dict:
    with open(SPEC, "rb") as f:
        return tomllib.load(f)["tokenizer"]


@dataclass
class SetBuild:
    """One build of one generated set, with the count of its own chunk files."""

    size: str
    variant: str
    set_folder: Path
    store: Path
    out: Path
    instances: dict[str, str]
    counted: dict
    # state -> the copy's store file, or the failure of its set-up
    states: dict[str, Path | Exception] = field(default_factory=dict)

    @property
    def shards(self) -> dict[str, str]:
        """The shards the replica registered: store name -> the replica's own name
        of the shard (``shard-01``), which names its files and the count's rows."""
        return {name: name.rsplit("/", 1)[1]
                for name in layout_shards(self.instances, LAYOUT, self.set_folder)}

    def need_shards(self) -> dict[str, str]:
        shards = self.shards
        if not shards:
            raise Unavailable(
                "not built yet: the replica registered no shard of the generated set (the hook "
                "point shard_tokenized of replica.capture_hooks)")
        return shards

    def chunk_file(self, shard: str) -> Path:
        return self.out / "pipeline" / LAYOUT / "tokenizer-input" / f"{shard}.jsonl"

    def prefix(self, shard: str) -> Path:
        return self.out / "pipeline" / LAYOUT / "shards" / shard

    def sanitizer_log(self) -> list[dict]:
        return read_rows(self.out / "pipeline" / LAYOUT / "sanitizer.log.jsonl")

    def counted_shard(self, part: str, shard: str) -> dict:
        """The row of one shard in ``documents`` or ``check3.drops`` of the count."""
        table = self.counted["documents"] if part == "documents" else self.counted["check3"][part]
        return next(entry for entry in table["shards"] if entry["shard"] == shard)


class Sets:
    """The generated sets of one test session, under one folder."""

    def __init__(self, base: Path) -> None:
        self.base = Path(base)
        self._sets: dict[str, Path] = {}
        self._builds: dict[tuple[str, str], SetBuild] = {}
        self._failed: dict[tuple[str, str], Exception] = {}
        self._plain: dict[str, tuple[Path, dict]] = {}
        self._tokenizer = None

    # --- Generating and counting ---------------------------------------------------------

    def set_folder(self, size: str) -> Path:
        if size not in self._sets:
            folder = self.base / size / "set"
            load_script("generate.py").generate(folder, dedup=DEDUP[size], **SIZES[size])
            self._sets[size] = folder
        return self._sets[size]

    def _count(self, size: str, out: Path, require_pair_kinds: str = "auto") -> dict:
        pipeline = out / "pipeline" / LAYOUT
        counting = load_script("count.py")
        try:
            return counting.count(self.set_folder(size), chunks=pipeline / "tokenizer-input",
                                  layout=LAYOUT, sanitizer_input=pipeline / "sanitizer-input",
                                  require_pair_kinds=require_pair_kinds)
        except counting.CountError as refusal:
            raise SetError(f"the counting script refuses the {size} set as the replica built "
                           f"it: {type(refusal).__name__}: {refusal}") from refusal

    def _replica(self, arguments: list[str], timeout: float) -> dict:
        env = {**os.environ, "PYTHONPATH": os.pathsep.join([str(REPO / "src"), str(REPO)])}
        root = megatron_root()
        if root is not None:
            env.setdefault("HF_HOME", str(root / "hf_home"))
            env.setdefault("HF_HUB_OFFLINE", "1")
        done = subprocess.run([sys.executable, "-m", "replica", *arguments], cwd=REPO, env=env,
                              capture_output=True, text=True, timeout=timeout)
        if done.returncode != 0:
            raise SetError(f"the replica ended with exit code {done.returncode}: "
                           f"{done.stderr[-600:]}")
        return json.loads(done.stdout)

    def chunked(self, size: str) -> tuple[Path, dict]:
        """The set chunked by the replica with no tokenization and no capture, and
        its count: enough for a question the plant list answers alone."""
        if size not in self._plain:
            out = self.base / size / "chunked"
            self._replica(["build-set", "--set", str(self.set_folder(size)), "--out", str(out),
                           "--layout", LAYOUT, "--no-tokenize"], BUILD_TIMEOUT[size])
            self._plain[size] = (out, self._count(size, out))
        return self._plain[size]

    # --- The two builds ------------------------------------------------------------------

    def build(self, size: str, variant: str) -> SetBuild:
        key = (size, variant)
        if key in self._failed:
            # A build that failed leaves its folder behind, and a second build into it
            # is refused for that reason: every row reports the first cause.
            raise self._failed[key]
        if key not in self._builds:
            try:
                self._builds[key] = (self._captured(size) if variant == CAPTURE
                                     else self._recovered(size))
            except Unavailable:
                raise
            except Exception as failure:
                self._failed[key] = failure
                raise
        return self._builds[key]

    def _captured(self, size: str) -> SetBuild:
        need_megatron()
        folder = self.base / size / CAPTURE
        store, out = folder / "store.sqlite", folder / "build"
        summary = self._replica(
            ["build-set", "--set", str(self.set_folder(size)), "--out", str(out), "--layout",
             LAYOUT, "--tokenizer-spec", str(SPEC), "--capture", "--store", str(store),
             "--jobs", str(JOBS)], BUILD_TIMEOUT[size])
        return SetBuild(size, CAPTURE, self.set_folder(size), store, out,
                        dict(summary["instances"]), self._count(size, out))

    def _recovered(self, size: str) -> SetBuild:
        from replica import fixture as replica_fixture

        recipe = getattr(replica_fixture, "build_set_store", None)
        if recipe is None:
            raise Unavailable(
                "not built yet: a generated set built without capture and recovered "
                "(replica.fixture.build_set_store)")
        need_megatron()
        built = recipe(self.base / size / NO_CAPTURE, self.set_folder(size), NO_CAPTURE,
                       layout=LAYOUT, tokenizer_spec=SPEC, parallel=JOBS)
        return SetBuild(size, NO_CAPTURE, self.set_folder(size), Path(built.store),
                        Path(built.out), dict(built.instances),
                        # The shuffles of a build made without capture are unseeded, so
                        # where a pair lies is not the plan's to fix: the count must not
                        # demand a same-shard pair of it (Check 3 asks the seeded build).
                        self._count(size, Path(built.out), require_pair_kinds="no"))

    # --- The team's tokenizer and the shard's own files ------------------------------------

    def tokenizer(self):
        """(tokenize, end-of-document id): Megatron's own tokenizer, built by the
        oracle as Megatron's preprocessing builds it. ``tokenize`` gives the ids of
        one text without the end-of-document token."""
        if self._tokenizer is None:
            root = need_megatron()
            os.environ.setdefault("HF_HOME", str(root / "hf_home"))
            os.environ.setdefault("HF_HUB_OFFLINE", "1")
            try:
                from oracle.config import TokenizerSpec
                from oracle.megatron_data import build_megatron_tokenizer
            except ImportError as missing:
                raise Unavailable("needs Megatron in the interpreter that runs the tests: "
                                  f"{missing}") from missing
            table = tokenizer_table()
            built = build_megatron_tokenizer(TokenizerSpec(
                type=table["type"], vocab_file=root / table["vocab_file"],
                merges_file=root / table["merges_file"]))
            self._tokenizer = (lambda text: [int(t) for t in built.tokenize(text)],
                               int(built.eod))
        return self._tokenizer

    def sizes(self, build: SetBuild, shard: str) -> list[int]:
        """The size of each document of a shard in the shard's own index, by
        ordinal, read with the replica's reader of the index file."""
        from replica.shard_index import read_shard_index

        return [n for n in read_shard_index(Path(f"{build.prefix(shard)}.idx")).document_tokens
                if n > 0]

    def check_planted_tokens(self, build: SetBuild, shard: str) -> None:
        """The outside half of "the planted record whose tokenization equals the
        shard's tokens at that ordinal": every chunk-file line, which the counting
        script accepted as its planted record's sanitized text, is tokenized by the
        team's tokenizer and held against the shard's tokens at its ordinal, read
        by Megatron's own reader. A difference means the count's list of records
        by ordinal does not describe this shard, and no row can be graded on it."""
        from oracle.megatron_data import open_shard

        tokenize, eod = self.tokenizer()
        end = [eod] if tokenizer_table()["eod_in_span"] else []
        lines = read_rows(build.chunk_file(shard))
        stored = open_shard(build.prefix(shard))
        if len(stored) != len(lines):
            raise SetError(f"{shard}: {len(stored)} documents, {len(lines)} chunk-file lines")
        for ordinal, line in enumerate(lines):
            if [int(t) for t in stored[ordinal]] != tokenize(line["text"]) + end:
                raise SetError(f"{shard} D{ordinal}: the shard's tokens are not the tokens of "
                               f"the planted record {line['id']} on line {ordinal + 1}")

    # --- The set-ups of Check 3, on a copy of the capture store ----------------------------

    def state(self, build: SetBuild, state: str) -> Path:
        """The store file of ``build`` in ``state``: a copy of the store file in a
        folder of its own, with the build folder linked beside it so that the
        relative paths the store holds still lead to the files."""
        if state not in build.states:
            folder = build.store.parent / "states" / state
            copied = folder / build.store.name
            try:
                folder.mkdir(parents=True)
                shutil.copyfile(build.store, copied)
                (folder / build.out.name).symlink_to(build.out, target_is_directory=True)
                _SETUPS[state](self, build, copied)
            except Exception as failure:
                # A set-up that failed is not tried again: every row of the state
                # then reports the first failure, not the folder it left behind.
                build.states[state] = failure
                raise
            build.states[state] = copied
        held = build.states[state]
        if isinstance(held, Exception):
            raise held
        return held

    def _settings(self):
        from waterwhite import tokenmap

        table = tokenizer_table()
        return tokenmap.TokenizerSettings(
            append_eod=table["append_eod"], eod_in_span=table["eod_in_span"],
            eod_token_id=table["eod_token_id"])

    def _recover(self, store, shard: str, input_name: str, *, both: bool):
        from waterwhite import tokenmap

        return tokenmap.recover_map(store, shard=shard, input=input_name,
                                    settings=self._settings(), tokenize=self.tokenizer()[0],
                                    also_token_matching=both)

    def _three_maps(self, build: SetBuild, copied: Path) -> None:
        """The position-mode and the token-matching recovery map of every shard,
        recovered from the registered tokenizer input, beside the capture map."""
        from waterwhite.store import Store

        store = Store.open(copied)
        try:
            for name in build.need_shards():
                self._recover(store, name, f"{name}.input", both=True)
        finally:
            store.close()


def swapped_lines(lines: list[str], pairs: list[dict]) -> list[str]:
    """The lines of a tokenizer input with the two lines of each pair exchanged."""
    out = list(lines)
    for pair in pairs:
        a, b = (member["line"] - 1 for member in pair["members"])
        out[a], out[b] = out[b], out[a]
    return out


def changed_first_line(lines: list[str]) -> list[str]:
    """The lines of a tokenizer input with line 1 replaced by the record of the
    set-up t.verification-fails. The line count stays."""
    row = json.dumps({"id": "changed-after-tokenization", "text": CHANGED_TEXT},
                     ensure_ascii=True)
    return [row, *lines[1:]]


def same_shard_pairs(counted: dict) -> dict[str, list[dict]]:
    """The identical pairs whose two members lie in one shard, by shard, from the
    counting script's pair list."""
    out: dict[str, list[dict]] = {}
    for pair in counted["check3"]["pairs"]["list"]:
        if pair["placement"] == "same-shard":
            out.setdefault(pair["members"][0]["shard"], []).append(pair)
    return out


def split_pairs(counted: dict) -> list[dict]:
    return [pair for pair in counted["check3"]["pairs"]["list"] if pair["placement"] == "split"]


def _read_lines(path: Path) -> list[str]:
    with open(path, encoding="utf-8", newline="\n") as f:
        return [line for line in f.read().split("\n") if line != ""]


def _register_changed(copied: Path, build: SetBuild, name: str, lines: list[str],
                      label: str, store) -> str:
    """Write a changed tokenizer input beside the copied store and register it as
    a file found afterwards. Returns the name it is registered under."""
    from waterwhite import recovery

    path = copied.parent / "changed" / label / f"{build.shards[name]}.jsonl"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("".join(line + "\n" for line in lines), encoding="utf-8", newline="\n")
    registered = f"{name}.input.{label}"
    recovery.register_found_file(store, path, name=registered)
    return registered


def _twin_swap(sets: Sets, build: SetBuild, copied: Path) -> None:
    """t.twin-swap: in every shard that holds both members of a pair, the pair's
    two lines change places in the tokenizer input, and the position-mode recovery
    is run on that input."""
    from waterwhite.store import Store

    shards = build.need_shards()
    by_shard = same_shard_pairs(build.counted)
    if not by_shard:
        raise SetError("no pair of the set has both members in one shard: nothing to swap")
    store = Store.open(copied)
    try:
        for name, shard in shards.items():
            if shard in by_shard:
                lines = swapped_lines(_read_lines(build.chunk_file(shard)), by_shard[shard])
                changed = _register_changed(copied, build, name, lines, "swapped", store)
                sets._recover(store, name, changed, both=False)
    finally:
        store.close()


def _verification_fails(sets: Sets, build: SetBuild, copied: Path) -> None:
    """t.verification-fails: line 1 of the tokenizer input of the first shard in
    name order is replaced after tokenization, and both recoveries are run on the
    changed input."""
    from waterwhite.store import Store

    name = next(iter(build.need_shards()))
    store = Store.open(copied)
    try:
        lines = changed_first_line(_read_lines(build.chunk_file(build.shards[name])))
        changed = _register_changed(copied, build, name, lines, "changed", store)
        sets._recover(store, name, changed, both=True)
    finally:
        store.close()


_SETUPS = {
    STATE_RECOVERED: Sets._three_maps,
    STATE_TWIN_SWAP: _twin_swap,
    STATE_VERIFICATION_FAILS: _verification_fails,
}
